"""Build viewer/stacks/<name>/frame_0..8.jpg + stacks/index.json from existing project outputs.
Run: python -I viewer/build_stacks.py   (needs Pillow)"""
import json, os
from PIL import Image
R = "D:/Refocus"; OUT = R + "/viewer/stacks"
stacks = []

def save(name, title, source, frames, note):
    d = f"{OUT}/{name}"; os.makedirs(d, exist_ok=True)
    for i, im in enumerate(frames):
        im.convert("RGB").save(f"{d}/frame_{i}.jpg", quality=92)
    stacks.append(dict(name=name, title=title, source=source, note=note, frames=[f"stacks/{name}/frame_{i}.jpg" for i in range(9)]))

def row(sheet, r):          # contact sheet: 9 columns x 2 rows (top = ground truth, bottom = model)
    im = Image.open(sheet); w, h = im.width // 9, im.height // 2
    return [im.crop((i * w, r * h, (i + 1) * w, (r + 1) * h)) for i in range(9)]

save("real_scene", "Real focal stack (dataset scene)", "real", [Image.open(f"{R}/remotion/public/frames/f{i}.jpg") for i in range(9)],
     "Ground-truth smartphone focal stack from the dataset (test-set scene).")
for p in (4, 1, 7):
    save(f"authors_in{p}", f"Authors' model, input position {p}", "model",
         row(f"{R}/results/eval_authors200k/sheet_in{p}.jpg", 1), f"Generated by the authors' 200k checkpoint from ONE input frame (position {p}).")
save("ours_random_in4", "Our model A (random), input position 4", "model", row(f"{R}/results/eval_armA_random/sheet_in4.jpg", 1),
     "Our 4,000-step ablation arm A, generated from one input frame (position 4).")
for n, t in (("macro", "Blender macro scene (ground truth)"), ("garden", "Blender garden (ground truth)"), ("still_life", "Blender still life (ground truth)")):
    save(f"blender_{n}", t, "blender", [Image.open(f"{R}/blender/renders/{n}/focal_position_{i:04d}.png") for i in range(9)],
         "Rendered with Cycles thin-lens depth of field; CC0 Poly Haven assets.")
os.makedirs(OUT, exist_ok=True)
json.dump(stacks, open(OUT + "/index.json", "w"), indent=1); print(len(stacks), "stacks")
